// The N=1 identity gate (#102 phase 5a-2, E9; brief section 4.1).
//
// WHAT IT HOLDS. Maintainer decision D2: **a user with one folder sees nothing new.** Below two folder
// pairs no node is added to the window, no frame moves, and the 22 header-spacer box assertions in the
// style gate stay exactly as drawn. That is a claim about TWO renderings of every frame, and nothing
// in the style gate can make it, because that gate compares one rendering against one drawing:
//
//   · the frame as authored — a fixture shaped like a daemon that predates folder pairs (no `pair`,
//     no `pairs`); that is 55 of the 63 (the other eight draw two folders on purpose — see below), and
//   · the same frame answered as a CURRENT daemon running one pair would answer it — `pair: "default"`
//     and a one-entry `pairs` on the reply, `selected`/`pairs`/`pair_states` on the payload, and a
//     `pairs` list on `read_config` (`?pairs=1`, handled in `fixtures/preview.js`).
//
// Every fixture reply is the first kind, so without this the one-pair app that real daemons produce
// is a rendering no gate has ever looked at. The two must be the same bytes: `outerHTML` of the app
// root, equal. DOM STRUCTURE (tags, classes, attributes, text) does not vary by platform the way
// sub-pixel boxes do, so equality needs no tolerance — and **no stored digest**, which would have to
// be regenerated by every legitimate edit and would only duplicate what the style gate already pins:
// the as-authored DOM is checked against the drawn frames there. This compares the app with itself.
//
// THE LIVE TRAY PANEL IS THE SECOND HALF, and it was missing until the review of #443. The `10a` frames
// MOUNT FROM THEIR FIXTURE'S ARGUMENTS (`mountFramePanel`) and never call `trayView`/`foldersOf`, so
// changing `foldersOf` to draw the folder group at ONE folder left all 55 frames identical — the only
// thing that noticed was a unit test. The panel the person actually gets is `?surface=tray`, polled
// from `tray_status`; it is rendered here once as a daemon that predates folder pairs answers it and
// once as a current daemon with one pair does, for the states the panel can be in, and the two must be
// the same bytes.
//
// WHAT IT CANNOT SEE, stated rather than implied: it renders the window and panel frames the style
// gate renders, once each way, and the live panel in the handful of states `LIVE_PANELS` lists. A screen
// state no frame draws is not looked at (the `firstRun` hero is one at the window — it is reachable only
// at two pairs, where nothing is drawn yet — though the live panel is asked for it), and a difference
// that appears only in the second poll of a live app is not a difference between two fixtures.
//
// A frame that does not render the same bytes twice from the SAME url is reported as such and fails
// the run: a comparison that cannot tell "the second rendering differs" from "this frame is not
// deterministic" would be a gate that fails at random and gets switched off.
//
// THAT SENTENCE WAS NOT TRUE UNTIL THE CLOCK WAS PINNED, and the reason is worth keeping next to the
// fix. `fixtures/clock.js` freezes `Date.now()` per page load, at whatever the machine's clock reads
// when that load runs, so two loads of one URL froze at two instants. Eight frames print an ABSOLUTE
// time from it (`9a Consent`'s `since ${clock(ago(60))}`), and CI rendered "since 15:17" and then
// "since 15:18" from the same URL when a minute fell between the loads: a red build that came and went
// with the second hand. Every load here now runs on one fixed instant (`clock-pin.mjs`), and each is
// ARMED WITH A REAL CLOCK A MINUTE AND A BIT LATER THAN THE LAST, which the pin hides from the page and
// which — if the pin ever stops holding — puts the minute boundary between every pair of loads rather
// than between one pair in three. A regression fails the same eight frames on every run.
// `FIDELITY_CLOCK_POISON=1` is that regression on demand.

import { readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import puppeteer from "puppeteer";
import { armClock, PINNED_NOW_MS, SKEW_STEP_MS } from "./clock-pin.mjs";
import { serve } from "./serve.mjs";
import { FIXTURES, resolveFixture } from "../../src/js/fixtures/frames.js";
import { withOnePair, withOnePairConfig } from "../../src/js/fixtures/preview.js";
import { EMPTY_CONFIG } from "../../src/js/api.js";

const HERE = dirname(fileURLToPath(import.meta.url));
const index = JSON.parse(readFileSync(join(HERE, "frames", "index.json"), "utf8"));

const { server, port } = await serve();
const browser = await puppeteer.launch({ headless: true, args: ["--no-sandbox"] });
const page = await browser.newPage();
// The window, as the style gate renders it. Nothing here is measured, but a layout-dependent branch
// (the squeeze gate re-opens compact frames at 200px) should see the same viewport it always does.
await page.setViewport({ width: 1040, height: 764, deviceScaleFactor: 1 });

/** How long the page may take to settle before it is called unsettled. */
const SETTLE_BUDGET_MS = 8000;

/**
 * The app root after it has stopped changing: three samples 100ms apart that are the same bytes AND
 * were each taken with no finite animation running. Both conditions are needed. Equal bytes alone span
 * only 200ms and the band entrance animation lasts 220ms (`--t-appear`), whose `animationend` handler is
 * what removes `is-entering`, so three equal samples could fall inside it and the next load's differed
 * (one run in ten under parallel load: `9a Consent`). An infinite animation (`breathe`, `blip`) is not
 * waited for: it never ends and changes no markup. A page that has not settled inside the budget FAILS
 * (`settled: false`); it is never passed.
 */
async function settledHtml(target = page) {
  const sample = () =>
    target.evaluate(() => ({
      html: document.getElementById("app-root")?.outerHTML ?? "",
      running: document
        .getAnimations()
        .filter((animation) => Number.isFinite(animation.effect?.getComputedTiming().endTime)).length,
    }));
  const deadline = Date.now() + SETTLE_BUDGET_MS;
  let last = "";
  let stable = 0;
  while (Date.now() < deadline) {
    const { html, running } = await sample();
    // A sample taken while something finite runs counts for nothing, not even as the first of three.
    stable = running > 0 ? 0 : stable > 0 && html === last ? stable + 1 : 1;
    last = html;
    if (stable >= 3) return { html: last, settled: true };
    await new Promise((resolve) => {
      setTimeout(resolve, 100);
    });
  }
  return { html: last, settled: false };
}

let loads = 0;
async function render(frame, query) {
  // The colour scheme is pinned exactly as the style gate pins it, or the machine's own default
  // would pick the theme and a frame could "differ" by the runner.
  await page.emulateMediaFeatures([
    { name: "prefers-color-scheme", value: frame.label.startsWith("12a") ? "light" : "dark" },
    { name: "prefers-reduced-motion", value: "no-preference" },
  ]);
  // The clock, and the skew that keeps the pin honest (see the header): this load's real clock reads
  // more than a minute after the previous load's, whatever the machine's actually did.
  await armClock(page, { realClockSkewMs: loads * SKEW_STEP_MS });
  loads += 1;
  await page.goto(`http://127.0.0.1:${port}/index.html?frame=${encodeURIComponent(frame.label)}${query}`, {
    waitUntil: "networkidle0",
  });
  await page.evaluate(() => localStorage.removeItem("theme"));
  await page.waitForSelector("#app-root > *", { timeout: 5000 }).catch(() => {});
  return settledHtml();
}

/** Where two strings first differ, with a little context on each side. */
function firstDifference(a, b) {
  let at = 0;
  while (at < a.length && at < b.length && a[at] === b[at]) at += 1;
  const around = (s) => JSON.stringify(s.slice(Math.max(0, at - 80), at + 120));
  return `at offset ${at} (lengths ${a.length} vs ${b.length})\n    authored: ${around(a)}\n    one pair: ${around(b)}`;
}

const problems = [];
let identical = 0;
/**
 * THE FRAMES THAT DRAW TWO FOLDERS OR MORE (#102 phase 5c-1), and why they are not in the comparison
 * below. A frame whose fixture lists two pairs has no one-folder rendering to be identical to:
 * `?pairs=1` would rewrite its reply as one folder and draw a different window, which is the point of
 * the frame and not a regression. They are still rendered twice from one URL (a frame that does not
 * settle to the same bytes twice is a finding whatever it draws), and what they carry for the claim is
 * everything else here — the 55 frames that list no folder, which are the ones a one-folder user has,
 * and the pill's absence at one folder, which the rest of this gate cannot see unless the pill is drawn
 * at one (poison: draw it at `pairs.length >= 1` and every frame below differs; at any count, and the
 * 22 frames that pin the header's `flex:1` spacer fail `assert.mjs`'s box compare).
 */
const atManyFolders = (label) => (resolveFixture(label)?.status?.pairs?.length ?? 0) >= 2;
const manyFolders = [];
/** What the folder selector's container looks like in the app root's markup. */
const PILL = 'class="pair-select"';
for (const frame of index) {
  const first = await render(frame, "");
  const second = await render(frame, "");
  if (!first.settled || !second.settled) {
    problems.push(`${frame.label}: never stopped changing, so there is nothing to compare`);
    continue;
  }
  if (first.html !== second.html) {
    problems.push(
      `${frame.label}: the SAME url rendered two different DOMs, so the comparison below means nothing\n  ` +
        firstDifference(first.html, second.html),
    );
    continue;
  }
  if (atManyFolders(frame.label)) {
    manyFolders.push(frame.label);
    // The positive control: a frame that lists two folders draws the selector, so the absence checked
    // below is the app's decision and not a pill that never renders anywhere.
    if (!first.html.includes(PILL))
      problems.push(`${frame.label}: lists two folders and draws no folder pill`);
    continue;
  }
  // THE PILL IS ABSENT, stated outright and not left to the comparison below. The two renderings are
  // equal if the pill is drawn in BOTH — a pill drawn unconditionally, or for a daemon that lists none,
  // would pass `withPair.html !== first.html` — and the style gate cannot see it either: the header's
  // `⋯` glyph is not in the bundled faces, so `boxComparability` takes the header's whole subtree out of
  // the box comparison (the spacer's `731.08` is recorded and asserted nowhere), and an extra node no
  // fixture names is stamped by nothing. Measured: with the pill drawn unconditionally `assert.mjs` still
  // reported 0 failures on `2a Settled` and `2a Syncing`. This line is what makes decision D2 a check.
  if (first.html.includes(PILL)) {
    problems.push(`${frame.label}: draws the folder pill for a daemon that lists no more than one folder`);
    continue;
  }
  const withPair = await render(frame, "&pairs=1");
  if (!withPair.settled) {
    problems.push(`${frame.label}: never stopped changing with one pair listed`);
    continue;
  }
  if (withPair.html.includes(PILL)) {
    problems.push(`${frame.label}: draws the folder pill with ONE pair listed`);
    continue;
  }
  if (withPair.html !== first.html) {
    problems.push(
      `${frame.label}: listing one pair changes what is drawn\n  ${firstDifference(first.html, withPair.html)}`,
    );
    continue;
  }
  identical += 1;
}

// ---- the live tray panel ----------------------------------------------------------------------------------

const LAST_SYNC = PINNED_NOW_MS / 1000 - 120;

/** A `tray_status` reply, as a daemon that predates folder pairs sends it: a state and no pair anywhere. */
const replyOf = (over = {}) => ({
  status: "running",
  paused: false,
  syncing: false,
  reconcile_seq: 1,
  pending_changes: 0,
  message: "",
  last_sync_epoch_secs: LAST_SYNC,
  last_error: null,
  last_plan_summary: null,
  last_successful_sync_summary: null,
  status_history: [],
  pending_deletions: [],
  failed_items: [],
  failed_item_count: 0,
  config: { local_root: "/home/u/Sync", remote_root: "/Drive/Sync", db_path: "/home/u/Sync/.sync/i.db" },
  activity: null,
  unsyncable: [],
  auth: "signed-in",
  ...over,
});
const payloadOf = (state, over) => ({ state, error: null, response: replyOf(over) });
const deletionOf = (path) => ({
  path,
  direction: "remote",
  entity_kind: "file",
  fingerprint: `fp-${path}`,
  detected_epoch_secs: LAST_SYNC,
  first_seen_epoch_secs: LAST_SYNC,
});

/**
 * The states the live panel is asked about. Each is drawn as a legacy daemon answers it and again as a
 * current daemon with one pair does; the two must be the same bytes. The set is every FORM the panel
 * has (settled, syncing, needs you by a deletion and by a conflict, paused, the struck mark three ways,
 * and the never-synced hero the tray draws where the window does not).
 */
const LIVE_PANELS = [
  { label: "up to date", status: payloadOf("idle") },
  {
    label: "syncing a transfer",
    status: payloadOf("running", {
      syncing: true,
      pending_changes: 3,
      activity: {
        phase: "executing",
        transfer: { path: "docs/spec.md", direction: "upload", bytes_done: null, bytes_total: 2048 },
      },
    }),
  },
  { label: "paused", status: payloadOf("paused", { paused: true, pending_changes: 7 }) },
  { label: "a failed pass", status: payloadOf("failed", { last_error: "boom", pending_changes: 4 }) },
  { label: "a deletion waiting", status: payloadOf("idle", { pending_deletions: [deletionOf("a.txt")] }) },
  {
    label: "a conflict waiting",
    status: payloadOf("idle"),
    conflicts: [{ original: "note.txt", sidecar: "note.proton-cloud.txt", kind: "content" }],
  },
  { label: "signed out", status: payloadOf("authExpired", { auth: "signed-out", pending_changes: 2 }) },
  { label: "never synced", status: payloadOf("firstRun", { last_sync_epoch_secs: null }) },
  { label: "no daemon", status: { state: "unreachable", response: null, error: "no socket" } },
];

/** The app root of `?surface=tray` once it has settled, answered by a scripted `tray_status`. */
async function liveTrayHtml({ status, conflicts = [] }, { onePair }) {
  const live = await browser.newPage();
  try {
    await live.setViewport({ width: 362, height: 640, deviceScaleFactor: 1 });
    await live.emulateMediaFeatures([
      { name: "prefers-color-scheme", value: "dark" },
      { name: "prefers-reduced-motion", value: "no-preference" },
    ]);
    await armClock(live, { realClockSkewMs: loads * SKEW_STEP_MS });
    loads += 1;
    await live.exposeFunction("__bridge", (cmd) => {
      switch (cmd) {
        case "tray_status":
        case "get_status":
        case "tray_action":
          return onePair ? withOnePair(status) : status;
        case "read_config":
          return onePair ? withOnePairConfig(EMPTY_CONFIG) : EMPTY_CONFIG;
        case "scan_conflicts":
          return conflicts;
        case "read_notify_policy":
          return "never";
        case "check_cli":
          return { installed: true, distro: null };
        default:
          return null;
      }
    });
    await live.evaluateOnNewDocument(() => {
      window.__listeners = {};
      // The injection Tauri makes, as an object literal (see `check-pair-routing.mjs`).
      Object.assign(window, {
        __TAURI__: {
          core: { invoke: (cmd, args) => window.__bridge(cmd, args ?? null) },
          event: {
            listen: (name, callback) => {
              window.__listeners[name] = callback;
              return Promise.resolve(() => {});
            },
          },
        },
      });
    });
    await live.goto(`http://127.0.0.1:${port}/index.html?surface=tray`, { waitUntil: "networkidle0" });
    await live.waitForSelector("#app-root > *", { timeout: 5000 }).catch(() => {});
    return await settledHtml(live);
  } finally {
    await live.close();
  }
}

let liveIdentical = 0;
for (const panel of LIVE_PANELS) {
  const first = await liveTrayHtml(panel, { onePair: false });
  const second = await liveTrayHtml(panel, { onePair: false });
  if (!first.settled || !second.settled || !first.html) {
    problems.push(`live tray panel, ${panel.label}: never drew, or never stopped changing`);
    continue;
  }
  if (first.html !== second.html) {
    problems.push(
      `live tray panel, ${panel.label}: the SAME payload rendered two different DOMs\n  ` +
        firstDifference(first.html, second.html),
    );
    continue;
  }
  const withPair = await liveTrayHtml(panel, { onePair: true });
  if (!withPair.settled) {
    problems.push(`live tray panel, ${panel.label}: never stopped changing with one pair listed`);
    continue;
  }
  if (withPair.html !== first.html) {
    problems.push(
      `live tray panel, ${panel.label}: listing one pair changes what is drawn\n  ${firstDifference(first.html, withPair.html)}`,
    );
    continue;
  }
  liveIdentical += 1;
}

await browser.close();
server.close();

if (problems.length) {
  console.error(
    `\nfidelity:n1 — ${problems.length} frame(s) or live panel(s) draw something new for a daemon that lists one pair:\n`,
  );
  for (const problem of problems) console.error(`  ${problem}\n`);
  console.error(
    "A one-folder user must see nothing new (D2). If this is a deliberate change it belongs at TWO pairs\n" +
      "or more, behind a `pairCount >= 2` the screen is handed; it is not a thing to record away here.",
  );
  process.exit(1);
}

/**
 * WHAT THE LISTING ACTUALLY REACHES, MEASURED: each fixture is handed to the injection the app itself
 * calls, and a reply counts as rewritten when what came back is not what went in. "55/55" reads as
 * fifty-five frames each rewritten end to end, and that is not what happens. The injection rewrites two
 * replies, and a frame only has what it has:
 *
 *   · the STATUS reply (`pair`, `pairs`, `selected`, `pair_states`) is rewritten on the frames whose
 *     fixture carries a status with a reply; a status with none gains `selected` alone (all Rust knows
 *     when the socket failed); and a frame that describes no status is answered by the generic mock,
 *     which the listing does not touch;
 *   · the `read_config` reply (`pairs`) is asked for by every frame's boot, from the frame's own config
 *     when it describes one and from the empty one when it does not. A config that already lists a pair
 *     keeps it, so only those that list none are rewritten.
 *
 * These were first counted from the fixtures with the same test the injection was thought to use, which
 * is how an injection that reached NO config reply printed the same figures as one that reached 46
 * (K8). The count now comes from `withOnePair`/`withOnePairConfig` themselves, and the gate refuses
 * to pass when either reached nothing: a comparison of replies the injection never touched is two
 * copies of one rendering.
 */
function reach() {
  const tally = {
    reply: 0,
    selectedOnly: 0,
    noStatus: 0,
    ownConfig: 0,
    emptyConfig: 0,
    configRewritten: 0,
    configAuthored: 0,
  };
  for (const { label } of index) {
    if (atManyFolders(label)) continue;
    const fixture = FIXTURES[label];
    if (!fixture.status) tally.noStatus += 1;
    else {
      const after = withOnePair(fixture.status);
      if (after.response !== fixture.status.response) tally.reply += 1;
      else if (after !== fixture.status) tally.selectedOnly += 1;
    }
    if (fixture.config) tally.ownConfig += 1;
    else tally.emptyConfig += 1;
    const served = fixture.config ?? EMPTY_CONFIG;
    if (withOnePairConfig(served) !== served) tally.configRewritten += 1;
    else tally.configAuthored += 1;
  }
  return tally;
}
const r = reach();
// The live panel's own: the injection must have rewritten the replies it was given, or its comparison
// was two copies of one rendering. Only the daemon-less payload has no reply to rewrite.
const liveRewritten = LIVE_PANELS.filter(
  ({ status }) => withOnePair(status).response !== status.response,
).length;
if (r.reply === 0 || r.configRewritten === 0 || liveRewritten === 0) {
  console.error(
    `fidelity:n1 — the one-pair injection reached nothing it should have (status reply rewritten on ${r.reply}, ` +
      `read_config rewritten on ${r.configRewritten}, live panel replies rewritten on ${liveRewritten}), so the ` +
      "comparison above compared replies with themselves.",
  );
  process.exit(1);
}
console.log(
  `fidelity:n1 — ${identical}/${index.length - manyFolders.length} frames render the same bytes with one pair listed\n` +
    `  ${manyFolders.length} more draw two folders or more and are compared with themselves alone (${manyFolders.join(", ")})\n` +
    `  the live tray panel (\`?surface=tray\`, which no frame mounts through): ${liveIdentical}/${LIVE_PANELS.length} states, ` +
    `the reply rewritten on ${liveRewritten}\n` +
    `  reach (measured by running the injection on every fixture): status reply rewritten on ${r.reply}, ` +
    `\`selected\` alone on ${r.selectedOnly}, no status on ${r.noStatus}; ` +
    `read_config rewritten on ${r.configRewritten} (${r.ownConfig} describe a config, ${r.emptyConfig} take the empty one), ` +
    `already listing a pair on ${r.configAuthored}`,
);
